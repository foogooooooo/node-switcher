const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const path = require('node:path');

exports.run = async (window, directory) => {
  await fs.mkdir(directory, { recursive: true });
  const evaluate = (code) => window.webContents.executeJavaScript(code, true);
  const errors = [];
  window.webContents.on('console-message', (_event, details) => { if (details.level === 'error') errors.push(details.message); });
  async function waitFor(code) {
    const until = Date.now() + 12000;
    while (Date.now() < until) {
      if (await evaluate(code)) return;
      await new Promise((r) => setTimeout(r, 100));
    }
    throw new Error(`UI timed out: ${code}`);
  }
  async function screenshot(name) {
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    const image = await window.webContents.capturePage(); await fs.writeFile(path.join(directory, name), image.toPNG());
  }
  await waitFor(`document.getElementById('client-badge').textContent === '已连接'`);
  assert.equal(await evaluate(`document.getElementById('match-options').open`), false);
  assert.equal(await evaluate(`document.getElementById('preview').disabled`), true);
  await screenshot('01-empty.png');
  await evaluate(`document.getElementById('website').value = '127.0.0.1'; document.getElementById('target').value = '日本 · 测试节点'; document.getElementById('add-form').requestSubmit();`);
  assert.match(await evaluate(`document.getElementById('form-error').textContent`), /不支持 IP/);
  assert.equal(await evaluate(`document.querySelectorAll('.route-row').length`), 0);
  await evaluate(`document.getElementById('target').value = ''; document.getElementById('target-search').value = '美国'; document.getElementById('target-search').dispatchEvent(new Event('input'));`);
  assert.deepEqual(await evaluate(`[...document.getElementById('target').options].map(o => o.value)`), ['', '美国 · 测试节点']);
  await evaluate(`document.getElementById('target').value = '美国 · 测试节点'; document.getElementById('target-search').value = '日本'; document.getElementById('target-search').dispatchEvent(new Event('input'));`);
  assert.equal(await evaluate(`document.getElementById('target').value`), '美国 · 测试节点', 'Filtering must never silently change the chosen exit');
  await evaluate(`document.getElementById('target-search').value = ''; document.getElementById('target-search').dispatchEvent(new Event('input'));`);
  await evaluate(`document.getElementById('website').value = 'https://example.com/path'; document.getElementById('target').value = '日本 · 测试节点'; document.getElementById('add-form').requestSubmit();`);
  await waitFor(`document.querySelectorAll('.route-row').length === 1`);
  await evaluate(`document.getElementById('website').value = 'news.example.com'; document.getElementById('match').value = 'exact'; document.getElementById('target').value = '美国 · 测试节点'; document.getElementById('add-form').requestSubmit();`);
  await waitFor(`document.querySelectorAll('.route-row').length === 2`);
  assert.equal(await evaluate(`document.getElementById('match').value`), 'suffix', 'New websites return to the disclosed default');
  await evaluate(`document.querySelector('.route-row button').click()`);
  assert.equal(await evaluate(`document.querySelectorAll('.route-row').length`), 1);
  await evaluate(`document.getElementById('undo-remove').click()`);
  assert.equal(await evaluate(`document.querySelectorAll('.route-row').length`), 2);
  await evaluate(`document.getElementById('website').value = 'unfinished.example.com'; document.getElementById('preview').click()`);
  await waitFor(`document.getElementById('form-error').textContent.includes('还没有加入列表') && !document.getElementById('preview').disabled`);
  assert.equal(await evaluate(`document.getElementById('preview-dialog').open`), false, 'Saving must not silently skip a website being entered');
  await evaluate(`document.getElementById('website').value = ''; document.getElementById('website').dispatchEvent(new Event('input'));`);
  assert.equal(await evaluate(`document.getElementById('preview').getBoundingClientRect().bottom < window.innerHeight`), true, 'Main action must stay visible');
  await screenshot('02-rules.png');
  await evaluate(`document.getElementById('preview').click()`);
  await waitFor(`document.getElementById('preview-dialog').open`);
  await screenshot('03-preview.png');
  assert.equal(await evaluate(`document.getElementById('preview-details').open`), false);
  assert.match(await evaluate(`document.getElementById('preview-changes').textContent`), /新增 2 个/);
  assert.match(await evaluate(`document.getElementById('preview-warnings').textContent`), /优先/);
  await evaluate(`document.getElementById('apply').click()`);
  await waitFor(`!document.getElementById('preview-dialog').open && document.getElementById('notice').textContent.includes('已应用 2 条')`);
  await screenshot('04-applied.png');
  const result = await evaluate(`window.routing.refresh()`);
  assert.equal(result.entries.length, 2); assert.equal(result.verified, true);
  await evaluate(`(async () => { const pendingRefresh = refreshIfIdle(); document.getElementById('website').value = 'keep.example.com'; document.getElementById('website').dispatchEvent(new Event('input')); await pendingRefresh; })()`);
  assert.equal(await evaluate(`document.getElementById('website').value`), 'keep.example.com', 'A refresh in flight must preserve new input');
  await evaluate(`document.getElementById('website').value = ''; document.getElementById('website').dispatchEvent(new Event('input')); (async () => { const pendingRefresh = refreshIfIdle(); document.querySelector('.route-row select').value = 'DIRECT'; document.querySelector('.route-row select').dispatchEvent(new Event('change')); await pendingRefresh; })()`);
  assert.equal(await evaluate(`document.querySelector('.route-row select').value`), 'DIRECT', 'A refresh in flight must preserve new list edits');
  await evaluate(`document.querySelector('.route-row select').value = 'DIRECT'; document.querySelector('.route-row select').dispatchEvent(new Event('change')); window.confirm = () => true; document.getElementById('discard-draft').click();`);
  assert.equal(await evaluate(`document.getElementById('preview').disabled`), true, 'Discard restores the applied baseline');
  // Exercise removal of every managed rule, then return without applying.
  await evaluate(`document.querySelector('.route-row button').click(); document.querySelector('.route-row button').click(); document.getElementById('preview').click();`);
  await waitFor(`document.getElementById('preview-dialog').open`);
  assert.match(await evaluate(`document.getElementById('preview-title').textContent`), /移除全部/);
  assert.match(await evaluate(`document.getElementById('preview-changes').textContent`), /删除 2 个/);
  await evaluate(`document.getElementById('cancel-preview').click(); document.getElementById('discard-draft').click();`);
  await evaluate(`document.querySelector('[data-page="history"]').click()`);
  await waitFor(`document.querySelector('[data-restore]') !== null`);
  await screenshot('05-history.png');
  await evaluate(`window.confirm = () => true; document.querySelector('[data-restore]').click()`);
  await waitFor(`document.getElementById('notice').textContent.includes('已恢复原文件')`);
  assert.equal((await evaluate(`window.routing.refresh()`)).entries.length, 0);
  await evaluate(`document.querySelector('[data-page="connection"]').click()`);
  await screenshot('06-connection.png');
  window.setSize(900, 680);
  await evaluate(`document.querySelector('[data-page="rules"]').click()`);
  await new Promise((r) => setTimeout(r, 200));
  assert.equal(await evaluate(`document.documentElement.scrollWidth > window.innerWidth`), false, 'Window must not overflow horizontally');
  assert.equal(await evaluate(`document.getElementById('preview').getBoundingClientRect().bottom <= window.innerHeight`), true, 'Save action stays visible at minimum window size');
  await screenshot('07-narrow.png');
  await evaluate(`notice(''); window.scrollTo(0, 0);`);
  await screenshot('07b-narrow-clean.png');
  assert.equal(await evaluate(`(() => { const rect = document.getElementById('add-rule').getBoundingClientRect(); return document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)?.closest('#add-rule') !== null; })()`), true, 'Add action must not be covered by the sticky save bar');
  await evaluate(`client.mode = 'global'; updateActions();`);
  assert.match(await evaluate(`document.getElementById('setup-title').textContent`), /规则模式/);
  assert.equal(await evaluate(`document.getElementById('preview').disabled`), true);
  await screenshot('08-needs-setup.png');
  await evaluate(`client.mode = 'rule'; demo = false; client.binary = null; updateActions();`);
  assert.match(await evaluate(`document.getElementById('setup-action').textContent`), /选择内核/);
  await evaluate(`connected = false; updateActions();`);
  assert.equal(await evaluate(`document.getElementById('add-rule').disabled`), true);
  assert.match(await evaluate(`document.getElementById('setup-title').textContent`), /连接中断/);
  await evaluate(`client = null; candidates = []; targetOptions(document.getElementById('target')); updateActions();`);
  assert.match(await evaluate(`document.getElementById('setup-title').textContent`), /先连接/);
  assert.equal(await evaluate(`document.getElementById('client-badge').textContent`), '未连接');
  await screenshot('09-first-connection.png');
  assert.deepEqual(errors, []);
  console.log('Electron UI smoke passed: inline validation, exit search, default scope, delete undo, unsaved input, preview, apply/readback, discard, clear-all preview, restore, minimum window, setup guidance.');
};
